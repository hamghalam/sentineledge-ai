
from enum import Enum
from sentineledge.tools.schemas import CalculatorArgs as CalculatorToolArgs

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    model_validator,
)


class PlannerAction(str, Enum):
    DIRECT_RESPONSE = "direct_response"
    TOOL_CALL = "tool_call"


class EmptyToolArgs(BaseModel):
    """Arguments for a direct response without tool execution."""

    model_config = ConfigDict(extra="forbid")


class CalculatorToolArgs(BaseModel):
    """Validated arguments for the calculator tool."""

    model_config = ConfigDict(
        extra="forbid",
        str_strip_whitespace=True,
    )

    expression: str = Field(min_length=1, max_length=100)


class PlannerProposal(BaseModel):
    """
    Structured proposal generated by the LLM planner.

    A planner proposal does not grant permission to execute a tool.
    """

    model_config = ConfigDict(
        extra="forbid",
        str_strip_whitespace=True,
    )

    action: PlannerAction

    tool_name: str | None = None

    tool_args: CalculatorToolArgs | EmptyToolArgs = Field(
        default_factory=EmptyToolArgs
    )

    @model_validator(mode="after")
    def validate_action_consistency(self):
        if self.action == PlannerAction.DIRECT_RESPONSE:
            if self.tool_name is not None:
                raise ValueError(
                    "direct_response cannot specify a tool_name."
                )

            if not isinstance(self.tool_args, EmptyToolArgs):
                raise ValueError(
                    "direct_response must have empty tool_args."
                )

        elif self.action == PlannerAction.TOOL_CALL:
            if self.tool_name != "calculator":
                raise ValueError(
                    "Unsupported tool. Only calculator is currently available."
                )

            if not isinstance(self.tool_args, CalculatorToolArgs):
                raise ValueError(
                    "Calculator requires CalculatorToolArgs."
                )

        return self
